"""Recorded demos: each DEMO.md trace as it came out on the day it was recorded.

A live demo traces live data, and live data moves -- DEMO.md trace 3 changed
attribution six times. A recording is the answer the demo was written about,
frozen, so it can be shown beside the live trace and the two compared.

Recordings come from data/recorded_demos.json, written by
scripts/record_demos.py. They are deliberately not cases: a case is a
complaint, and twelve permanent demo rows would show up in every correlation
as repeat complaints that nobody made."""

from __future__ import annotations

import json
from functools import lru_cache
from typing import Any

from fastapi import APIRouter, HTTPException, Query
from fastapi.responses import JSONResponse, PlainTextResponse

from .. import config, request_letters
from ..contracts import on_read

router = APIRouter()

RECORDED_DEMOS_PATH = config.DATA_DIR / "recorded_demos.json"


@lru_cache(maxsize=1)
def _recordings() -> dict[int, dict[str, Any]]:
    try:
        rows = json.loads(RECORDED_DEMOS_PATH.read_text())
    except (OSError, ValueError):
        return {}
    return {int(row["demo"]): row for row in rows}


@router.get("/demos/recorded")
def list_recorded() -> dict[str, Any]:
    """Which demos have a recording, and what each one found: the exchange,
    and whether it was inferred (a probable deposit address, not a label
    match), so a link that names it can say so."""
    return {"demos": [
        {
            "demo": n,
            "recorded_at": row["recorded_at"],
            "address": row["result"].get("address"),
            "exchange": row["result"].get("exchange"),
            "attribution_inferred": bool(row["result"].get("attribution_inferred")),
            "confidence": row["result"].get("confidence"),
        }
        for n, row in sorted(_recordings().items())
    ]}


@router.get("/demos/recorded/{demo}", response_model=None)
def get_recorded(demo: int) -> JSONResponse:
    """One recorded demo, in the shape of a stored case but with no case id:
    nothing that writes to a case (watches, request logs) applies. Its
    letters are drafted below, marked as examples.

    Recordings predate the victim flow, freeze dates and which wallets the
    walk read, so they are added here (contracts.on_read), for each follow-on
    too, and the case is rendered here as well: both in the worker thread, as
    GET /trace/{id} does, never on the event loop."""
    row = _recordings().get(demo)
    if row is None:
        raise HTTPException(status_code=404, detail=f"No recording for demo {demo}")
    return JSONResponse({**on_read(row["result"]), "case_id": None,
                         "created_at": row["recorded_at"], "recorded_demo": demo})


def _recording(demo: int) -> dict[str, Any]:
    row = _recordings().get(demo)
    if row is None:
        raise HTTPException(status_code=404, detail=f"No recording for demo {demo}")
    return {**row["result"], "created_at": row["recorded_at"]}


@router.get("/demos/recorded/{demo}/letters")
def recorded_letters(demo: int) -> dict[str, Any]:
    """The letters a recording supports, as GET /trace/{id}/letters lists a
    case's: the Letters tab shows them, though none can be logged as sent."""
    return {"case_id": None, "recorded_demo": demo, "letters": request_letters.available(_recording(demo))}


@router.get("/demos/recorded/{demo}/letter")
def recorded_letter(demo: int, to: str = Query(..., max_length=32)) -> PlainTextResponse:
    """A recording's draft letter, drafted as a case's is, then marked as an
    example (_as_example). Public, as the recording is; nothing is kept."""
    result = _recording(demo)
    try:
        return PlainTextResponse(_as_example(request_letters.draft(f"demo-{demo}", result, to), demo))
    except ValueError as exc:  # an unknown letter, or one the recording cannot support
        raise HTTPException(status_code=400, detail=str(exc)) from exc


def _as_example(text: str, demo: int) -> str:
    """A letter from a recording says it is an example from no stored case,
    and drops the lines that send its reader to check a signed report: a
    public page has none to attach."""
    text = text.replace("Generated by Exchequer from a stored case.",
                        f"Drafted by Exchequer from recorded example {demo}, not from a stored case.\n"
                        "Example only: do not send.")
    text = text.replace(f"Exchequer case demo-{demo}", f"Exchequer recorded example {demo}")
    text = text.replace(f"case demo-{demo}", f"recorded example {demo}")
    lines = text.split("\n")
    out = []
    for n, line in enumerate(lines):
        if line.startswith("Check the attached report only at") or (
                line.startswith("Ed25519 key") and n and lines[n - 1].startswith("Check the attached report")):
            continue
        out.append(line)
    return "\n".join(out)
