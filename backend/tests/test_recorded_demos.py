# A recording is no case, but the Letters tab still shows the letters it
# supports, drafted from the recording; nothing is stored or logged to a case.
def test_recorded_letters_list_what_the_recording_supports(client):
    body = client.get("/demos/recorded/11/letters").json()
    assert body["recorded_demo"] == 11
    assert body["case_id"] is None
    # The urgent freeze letters first, as a stored case lists them.
    assert [letter["to"] for letter in body["letters"]] == ["exchange-freeze", "tether-freeze", "exchange", "tether"]
    assert body["letters"][0]["title"] == "Urgent freeze request to Binance"
    assert body["letters"][2]["title"] == "Request to Binance"


def test_recorded_letter_is_drafted_from_the_recording(client):
    before = len(models.all_cases())
    response = client.get("/demos/recorded/11/letter", params={"to": "exchange"})
    assert response.status_code == 200
    assert response.headers["content-type"].startswith("text/plain")
    text = response.text
    assert "TDqSquXBgUCLYvYC4XZgrprLK589dkhSCf" in text
    assert "about 635.000000 USDT" in text
    assert len(models.all_cases()) == before


# A recording is public and no stored case: its letter must not read as a
# ready draft from one, nor point at a signed report no one can check.
def test_recorded_letter_says_it_is_an_example_from_no_stored_case(client):
    for to in ("exchange-freeze", "tether-freeze", "exchange", "tether"):
        text = client.get("/demos/recorded/11/letter", params={"to": to}).text
        assert "This is a DRAFT. It is not valid until an officer signs it on official letterhead." in text
        assert "Generated by Exchequer from a stored case" not in text
        assert "Drafted by Exchequer from recorded example 11, not from a stored case." in text
        assert "Example only: do not send." in text
        assert "demo-11" not in text
        if not to.endswith("-freeze"):  # a freeze letter names no case, only what to hold
            assert "Exchequer recorded example 11, traced" in text
        assert "Check the attached report" not in text
        assert "Ed25519" not in text
        assert "[____" in text  # the blanks stay, for the officer to see what a letter asks


