"""The bank-hold notice's wording behind EXCHEQUER_FREEZE_WORDING_V2 (#251).

Courts differ on whether the police may hold money in a bank without a
Magistrate's order (docs/legal/freeze-wording-review.md). Today's letter asks
for a "debit freeze ... up to the amount", which mixes a freeze of the account
with a lien on an amount. With the flag on, the letter rests on the Magistrate's
order alone: the bank is asked to give effect to the attached order as it
directs, for no more than the amount stated. With the flag off, the letter is
byte for byte what it was before the flag existed.
"""
from __future__ import annotations

import hashlib
from datetime import datetime, timezone

import pytest

from app import config, request_letters
from app.notice_letters import BANK_FREEZE, BANK_INFO, TELECOM, NoticeError, draft, fingerprint
from app.request_letters import AWAITING, BLANK, NOT_VALID

from test_notice_letters import ACCOUNT, IFSC, ORDER, OWNER, bank, client, hold, telecom  # noqa: F401 -- client is a fixture
from test_request_letters import case

APPROVAL = {"by": "SI Rao", "at": "2026-11-12T05:30:00+00:00"}

# The letter on main before this flag, drafted on 15 Nov 2026 from hold(). Pinned, not regenerated.
BEFORE = """\
DRAFT — URGENT freeze request, for the investigating officer to complete and sign.
This is a DRAFT. It is not valid until an officer signs it on official letterhead.
Awaiting a second officer's approval: not ready to send until one of this unit approves it.
Details fingerprint: cbd1f079ffcbb2f6 (a second officer's sign-off covers these exact details)
Generated by Exchequer from a stored case. Nothing below has been sent.

From      : [____________________] (officer's name and rank)
Station   : [____________________] (police station / cyber cell)
Reference : [____________________] (FIR / NCRP acknowledgement number)
Contact   : [____________________] (official e-mail and phone)
Date      : 15 November 2026
To        : The Nodal Officer, State Bank of India

Subject   : URGENT — debit freeze on account 123456789012, pending a formal request

Under [____________________] (the legal provision this request is made under, officer to state):
   Please place a debit freeze, now, on account 123456789012 (IFSC SBIN0001234) up to the
   amount below, pending a formal request from this office.

Account   : 123456789012
IFSC      : SBIN0001234
Amount    : up to INR 2,50,000.00
Order     : Order 17/2026 dated 11 Nov 2026, JMFC Court, Bengaluru (copy attached)
Source    : Binance reply ref LE-2026-0042 dated 10 Nov 2026

Please confirm the hold and the balance held to the contact above.

[____________________]
(signature, name, rank, seal)
"""
# The same, SHA-256 of the signed-off letter and of one with the amount left blank.
BEFORE_APPROVED = "805295df904b963e5bddc37d9055415f48fce18c2ab7dc55507bde5fd04c9f3b"
BEFORE_NO_AMOUNT = "2b31c61bf43627612621f62957faf754424188df67b68b9f6798c82efc85c6aa"
BEFORE_REFUSAL = "A bank hold attaches money, which needs a Magistrate's order: enter its number, date and court."


@pytest.fixture
def on_15_nov(monkeypatch):
    monkeypatch.setattr(request_letters, "_utc_now", lambda: datetime(2026, 11, 15, 6, 0, tzinfo=timezone.utc))


@pytest.fixture
def v2(monkeypatch):
    monkeypatch.setattr(config, "FREEZE_WORDING_V2", True)


@pytest.fixture
def v1(monkeypatch):
    monkeypatch.setattr(config, "FREEZE_WORDING_V2", False)


def sha(text):
    return hashlib.sha256(text.encode()).hexdigest()


def flat(text):
    return " ".join(text.split())


def test_the_flag_is_registered_and_described():
    assert "EXCHEQUER_FREEZE_WORDING_V2" in config.FLAGS
    assert "Magistrate's order" in config.FLAGS["EXCHEQUER_FREEZE_WORDING_V2"]["about"]


# -- flag off: nothing changes ----------------------------------------------------------
def test_flag_off_the_bank_hold_is_byte_identical_to_before(on_15_nov, v1):
    assert draft("case-1", case(), BANK_FREEZE, hold()) == BEFORE
    assert sha(draft("case-1", case(), BANK_FREEZE, hold(), APPROVAL)) == BEFORE_APPROVED
    assert sha(draft("case-1", case(), BANK_FREEZE, hold(amount=None))) == BEFORE_NO_AMOUNT


def test_flag_off_the_refusal_without_an_order_is_unchanged(v1):
    with pytest.raises(NoticeError) as refused:
        draft("case-1", case(), BANK_FREEZE, hold(order=""))
    assert str(refused.value) == BEFORE_REFUSAL


# -- flag on: the letter rests on the Magistrate's order --------------------------------
def test_flag_on_the_letter_asks_the_bank_to_act_on_the_order_as_it_directs(on_15_nov, v2):
    text = draft("case-1", case(), BANK_FREEZE, hold())
    assert "debit freeze" not in text.lower() and "freeze" not in text.lower()
    assert "lien" not in text.lower()  # the letter names no action of its own: the order does
    assert text.startswith("DRAFT — URGENT request under a Magistrate's order")
    assert "URGENT — action on account 123456789012 under a Magistrate's order" in text
    assert ("Please give effect, now, to the attached order of the Magistrate on account 123456789012 "
            "(IFSC SBIN0001234), as that order directs and for no more than the amount below") in flat(text)
    assert "Amount    : up to INR 2,50,000.00" in text and f"Order     : {ORDER} (copy attached)" in text
    assert "what was done under the order and the balance it covers" in text


def test_flag_on_the_provision_stays_a_blank_with_a_suggestion_for_the_officer(v2):
    text = flat(draft("case-1", case(), BANK_FREEZE, hold()))
    assert f"Under {BLANK} (the legal provision this request is made under, officer to state):" in text
    assert ("[e.g. Section 107 of the Bharatiya Nagarik Suraksha Sanhita, 2023, as the order states — "
            "officer to confirm]") in text


def test_flag_on_the_draft_keeps_every_safeguard(v2):
    text = draft("case-1", case(), BANK_FREEZE, hold())
    assert NOT_VALID in text and AWAITING in text
    assert f"Details fingerprint: {fingerprint('case-1', BANK_FREEZE, hold())[:16]}" in text
    assert "Approved by a second officer: SI Rao" in draft("case-1", case(), BANK_FREEZE, hold(), APPROVAL)
    assert f"Amount    : {BLANK} (officer to state)" in draft("case-1", case(), BANK_FREEZE, hold(amount=None))
    for claim in ("certified", "court-admissible", "CFCFRMS"):
        assert claim.lower() not in text.lower()


def test_flag_on_a_hold_is_still_refused_without_the_order(v2):
    with pytest.raises(NoticeError, match="Magistrate's order") as refused:
        draft("case-1", case(), BANK_FREEZE, hold(order="  "))
    assert "attaches money" not in str(refused.value)


def test_the_wording_does_not_change_what_a_sign_off_covers(monkeypatch):
    before = fingerprint("case-1", BANK_FREEZE, hold())
    monkeypatch.setattr(config, "FREEZE_WORDING_V2", True)
    assert fingerprint("case-1", BANK_FREEZE, hold()) == before


@pytest.mark.parametrize("to, details", [(BANK_INFO, bank()), (TELECOM, telecom())])
def test_the_flag_leaves_the_information_notices_alone(on_15_nov, monkeypatch, to, details):
    off = draft("case-1", case(), to, details)
    monkeypatch.setattr(config, "FREEZE_WORDING_V2", True)
    assert draft("case-1", case(), to, details) == off


def test_the_route_drafts_the_new_wording_with_the_flag_on(client, v2):  # noqa: F811 -- the imported fixture
    r = client.post("/trace/case-1/notice", json={"to": BANK_FREEZE, **hold()}, headers=OWNER)
    assert r.status_code == 200 and "give effect, now, to the attached order" in flat(r.text)
    assert ACCOUNT in r.text and IFSC in r.text and "debit freeze" not in r.text
